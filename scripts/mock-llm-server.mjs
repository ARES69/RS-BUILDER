/**
 * Scripted OpenAI-compatible mock LLM for local E2E (dev tool, not deployed).
 *
 * It drives a REAL run through the orchestrator's tool loop using the real
 * sandbox: run_shell scaffolds the project, run_code (a real node process)
 * generates data and CSS, edit_file patches the page, deliver_artifact ships
 * it. Used by scripts/qa-sandbox.mjs to prove the whole stack without burning
 * provider quota.
 *
 *   node scripts/mock-llm-server.mjs [port]
 */
import { createServer } from 'node:http'

const PORT = Number(process.argv[2] ?? 8791)
const MODEL = process.env.MOCK_MODEL ?? 'mock-builder'

let calls = 0
const tc = (name, args) => [{ id: 'call_' + ++calls, type: 'function', function: { name, arguments: JSON.stringify(args) } }]

/* The page the "model" builds — deliberately generated by a node script
   inside the sandbox, so the run proves real code execution end to end. */
