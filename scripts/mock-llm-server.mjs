const PATCH_STEP = {
  path: 'site/index.html',
  old_text: '<h1>Maroon Coffee</h1>',
  new_text: '<h1>Maroon Coffee <span style="color:#c8f751">·</span> v2</h1>',
}

function script(messages) {
  const execFlags = messages.map((m) => m.role === 'user' && String(m.content).startsWith('Execute step'))
  const step = execFlags.filter(Boolean).length || 0
  const lastExec = execFlags.lastIndexOf(true)
  const inStep = lastExec >= 0 ? messages.slice(lastExec + 1).filter((m) => m.role === 'tool').length : 0
  const hasPlan = messages.some((m) => m.role === 'assistant' && (m.tool_calls ?? []).some((c) => c.function.name === 'submit_plan'))

  if (!hasPlan) {
    return {
      content: 'Соберу лендинг кофейни настоящими инструментами песочницы.',
      tool_calls: tc('submit_plan', {
        intro: 'Соберу лендинг кофейни: каркас через шелл, данные и стили — настоящим node-скриптом, затем патч и выдача артефакта.',
        steps: [
          { title: 'Каркас проекта в песочнице', estimate: '30s' },
          { title: 'Данные, стили и скрипт через node', estimate: '40s' },
          { title: 'Патч и выдача артефакта', estimate: '20s' },
        ],
      }),
    }
  }

  if (step === 1) {
    if (inStep === 0) return { content: null, tool_calls: tc('think', { text: 'Начну с настоящей файловой системы: создам каталог сайта через шелл.' }) }
    if (inStep === 1) return { content: null, tool_calls: tc('run_shell', { note: 'каркас проекта', command: 'mkdir -p site && pwd && node -v && echo "sandbox ready"' }) }
    return { content: null, tool_calls: tc('step_done', { summary: 'каталог site создан, node доступен' }) }
  }

  if (step === 2) {
    if (inStep === 0) return { content: null, tool_calls: tc('run_code', { note: 'генерирую страницу, данные и стили node-скриптом', code: BUILD_SCRIPT, timeout_s: 20 }) }
    if (inStep === 1) return { content: null, tool_calls: tc('run_shell', { command: 'ls -l site && wc -c site/index.html site/styles.css site/app.js && node -e "const d=require(\'./site/data.json\'); console.log(\'menu items:\', d.menu.length)"' }) }
    return { content: null, tool_calls: tc('step_done', { summary: 'index.html + styles.css + app.js + data.json собраны node-скриптом' }) }
  }

  if (inStep === 0) return { content: null, tool_calls: tc('edit_file', PATCH_STEP) }
  if (inStep === 1) return { content: null, tool_calls: tc('run_shell', { command: 'grep -c card site/index.html && head -c 120 site/index.html' }) }
  return { content: null, tool_calls: tc('deliver_artifact', { title: 'Maroon Coffee — лендинг из песочницы', from_file: 'site/index.html', note: 'Собрано node-скриптом в настоящей песочнице' }) }
}

const server = createServer((req, res) => {
  let body = ''
  req.on('data', (c) => (body += c))
  req.on('end', () => {
    if (req.method === 'GET' && req.url?.includes('/models')) {
      res.setHeader('content-type', 'application/json')
      return res.end(JSON.stringify({ data: [{ id: MODEL }] }))
    }
    let payload = {}
    try { payload = JSON.parse(body || '{}') } catch { /* ignore */ }
    const move = script(payload.messages ?? [])
    res.setHeader('content-type', 'application/json')
    res.end(JSON.stringify({ id: 'mock-' + Date.now(), model: payload.model ?? MODEL, choices: [{ message: { role: 'assistant', content: move.content, tool_calls: move.tool_calls } }] }))
  })
})

server.listen(PORT, () => console.log('mock LLM (sandbox scenario) on http://127.0.0.1:' + PORT + '/v1'))
